export const featuredProjects = projects.filter(
  (project) => project.featured && !project.isPlaceholder,
);

export function getProjectBySlug(slug: string): Project | undefined {
  return projects.find((project) => project.slug === slug);
}

export function getProjectsByLocationTag(location: string): Project[] {
  return projects.filter((project) =>
    (project.locationTags as readonly string[]).includes(location),
  );
}

export function getAdjacentProjects(slug: string): {
  previous: Project;
  next: Project;
} | null {
  const current = projects.find((project) => project.slug === slug);

  if (!current) return null;

  const cohort = projects.filter(
    (project) => project.isPlaceholder === current.isPlaceholder,
  );
  const index = cohort.findIndex((project) => project.slug === slug);

  if (index === -1) return null;

  return {
    previous: cohort[(index - 1 + cohort.length) % cohort.length],
    next: cohort[(index + 1) % cohort.length],
  };
}
